import type { DiagnosticIssue, ConversionMetrics, ConversionReadiness } from './types.ts';

export function getConversionReadiness(diagnostics: DiagnosticIssue[]): ConversionReadiness {
  const blockingIssues = diagnostics.filter(issue => issue.severity === 'error' || issue.severity === 'manual-fix').length;
  const reviewIssues = diagnostics.filter(issue => issue.severity === 'warning' || issue.severity === 'unverified').length;
  return {
    status: blockingIssues > 0 ? 'blocked' : reviewIssues > 0 ? 'needs-review' : 'static-clean',
    blockingIssues,
    reviewIssues,
    nativeRuntimeVerified: false,
  };
}

