export function generateConversionReportMd(
  diagnostics: DiagnosticIssue[],
  metrics: ConversionMetrics,
  projectName: string = 'VaCuus Project'
): string {
  const errors = diagnostics.filter(d => d.severity === 'error');
  const warnings = diagnostics.filter(d => d.severity === 'warning');
  const manualFixes = diagnostics.filter(d => d.severity === 'manual-fix');
  const infos = diagnostics.filter(d => d.severity === 'info');
  const unverified = diagnostics.filter(d => d.severity === 'unverified');
  const readiness = getConversionReadiness(diagnostics);
  const readinessLabel = readiness.status === 'blocked'
    ? 'Blocked — fix errors/manual conversions before UE5 validation'
    : readiness.status === 'needs-review'
      ? 'Needs review — warnings/unverified features remain'
      : 'Static checks clean — UE5/VaCuus runtime still unverified';

  const lines: string[] = [
    `# Compatibility Report — ${projectName}`,
    `Generated by Kormatal RML UI Editor on ${new Date().toISOString()}`,
    '',
    '## Executive Summary',
    `- **Status:** ${readinessLabel}`,
    `- **HTML Tags Processed:** ${metrics.htmlTagsProcessed}`,
    `- **CSS Rules Analyzed:** ${metrics.cssRulesProcessed}`,
    `- **CSS Declarations Analyzed:** ${metrics.cssDeclarationsAnalyzed}`,
    `- **CSS Features Requiring Review:** ${metrics.cssUnsupportedFeatures}`,
    `- **JS Functions Analyzed:** ${metrics.jsFunctionsProcessed}`,
    `- **Browser APIs Flagged:** ${metrics.jsBrowserApisFlagged}`,
    `- **Unsupported HTML Elements:** ${metrics.htmlUnsupportedElements}`,
    `- **Auto-Fixes Applied:** ${metrics.autoFixesApplied}`,
    `- **Errors:** ${errors.length}`,
    `- **Warnings:** ${warnings.length}`,
    `- **Manual Fixes Needed:** ${manualFixes.length}`,
    '',
    '## Verification Status',
    '- **Browser Preview:** Emulated and rendered in sandboxed browser iframe.',
    '- **VaCuus Runtime Rules:** Statically verified against RmlUi/VaCuus engine catalog.',
    `- **Unreal Engine 5 Target:** Native runtime verification = ${readiness.nativeRuntimeVerified ? 'complete' : 'not performed'}; static conversion alone cannot establish visual/behavioral parity.`,
    '',
    '## Issues & Diagnosed Gotchas',
  ];

  if (diagnostics.length === 0) {
    lines.push('🎉 **No known static compatibility issues detected.** This is not a 100% runtime guarantee; verify the package in the exact UE5/VaCuus build.');
  } else {
    diagnostics.forEach((d, i) => {
      lines.push(`### [${d.severity.toUpperCase()}] ${d.category.toUpperCase()}: ${d.message}`);
      lines.push(`- **Location:** ${d.file}:${d.line}`);
      lines.push(`- **Snippet:** \`${d.originalSnippet}\``);
      lines.push(`- **Impact:** ${d.impact}`);
      lines.push(`- **Recommended Action:** ${d.recommendedAction}`);
      if (d.autoFixAvailable) {
        lines.push(`- **Auto-Fix:** ${d.fixed ? 'Applied' : 'Available'} (${d.autoFixDescription || 'Automated replacement'})`);
      }
      lines.push('');
    });
  }

  return lines.join('\n');
}

export function generateCompatibilityJson(diagnostics: DiagnosticIssue[], metrics: ConversionMetrics): string {
  const readiness = getConversionReadiness(diagnostics);
  return JSON.stringify(
    {
      version: '1.0.0',
      timestamp: new Date().toISOString(),
      engineTarget: 'Unreal Engine 5 (VaCuus / RmlUi)',
      readiness,
      metrics,
      diagnostics,
    },
    null,
    2
  );
}

import type { DataModelInfo } from './html-to-rml.ts';

export function generateUeCppHeader(screenName: string = 'MainUI', dataModelInfo?: DataModelInfo): string {
  const safeName = screenName.replace(/[^a-zA-Z0-9_]/g, '');
  const modelName = dataModelInfo?.modelName || (dataModelInfo?.bindings?.length ? `${safeName}Model` : '');

  let structDefinition = '';
  if (dataModelInfo && (dataModelInfo.modelName || dataModelInfo.bindings.length > 0)) {
    const rawFields = dataModelInfo.bindings.filter(b => !b.includes('.'));
    const fieldLines = rawFields.length > 0
      ? rawFields.map(b => {
          const cleanProp = b.replace(/[^a-zA-Z0-9_]/g, '');
          const lower = cleanProp.toLowerCase();
          if (lower.includes('health') || lower.includes('mana') || lower.includes('shield') || lower.includes('percent')) {
            return `    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "VaCuus|DataModel")\n    float ${cleanProp} = 100.0f;`;
          }
          if (lower.includes('ammo') || lower.includes('kills') || lower.includes('score') || lower.includes('rank') || lower.includes('level') || lower.includes('ping')) {
            return `    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "VaCuus|DataModel")\n    int32 ${cleanProp} = 0;`;
          }
          return `    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "VaCuus|DataModel")\n    FString ${cleanProp} = TEXT("Default");`;
        }).join('\n\n')
      : `    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "VaCuus|DataModel")\n    FString PlayerName = TEXT("Commander");\n\n    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "VaCuus|DataModel")\n    float Health = 100.0f;\n\n    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "VaCuus|DataModel")\n    float Mana = 100.0f;`;

    structDefinition = `
/**
 * F${safeName}DataModel
 * Unreal Engine Data Model struct bound to RML expressions (data-model="${modelName}").
 * In VaCuus, changes to this struct automatically propagate to RML {{expressions}}.
 */
USTRUCT(BlueprintType)
struct F${safeName}DataModel
{
    GENERATED_BODY()

${fieldLines}
};
`;
  }

  return `// Copyright (c) 2026. Generated by Kormatal RML UI Editor for Unreal Engine 5.
#pragma once

#include "CoreMinimal.h"
#include "VaCuusView.h"
#include "${safeName}View.generated.h"
${structDefinition}
/**
 * UVaCuus${safeName}View
 * Manages active UI lifecycle, data-model binding, and input routing for ${safeName}.
 * 
 * CRITICAL VACUUS / RMLUI RULES:
 * 1. Data models MUST be bound before calling LoadDocument().
 * 2. Input mode must be set to FInputModeGameAndUI to enable mouse/touch clicks on UI buttons.
 * 3. File paths resolve relative to Content/DevUI/.
 */
UCLASS(BlueprintType, Blueprintable, ClassGroup = (VaCuus), meta = (BlueprintSpawnableComponent))
class UVaCuus${safeName}View : public UVaCuusView
{
    GENERATED_BODY()

public:
    UVaCuus${safeName}View();

    /** Initializes and loads the active ${safeName} UI into the viewport */
    UFUNCTION(BlueprintCallable, Category = "VaCuus|UI")
    bool InitializeActiveUI(APlayerController* PlayerController, int32 ZOrder = 10);

    /** Closes document and safely releases input focus */
    UFUNCTION(BlueprintCallable, Category = "VaCuus|UI")
    void CloseActiveUI(APlayerController* PlayerController);

    /** Relative path to entry RML document from Content/DevUI/ */
    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "VaCuus|Config")
    FString DocumentPath = TEXT("${safeName}/${safeName.toLowerCase()}.rml");

    /** Automatically routes mouse and keyboard input to UI upon initialization */
    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "VaCuus|Config")
    bool bConfigureInputModeOnOpen = true;
${structDefinition ? `\n    /** Active Data Model bound to RML expressions */\n    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "VaCuus|DataModel")\n    F${safeName}DataModel DataModel;\n` : ''}};
`;
}

export function generateUeCppSource(screenName: string = 'MainUI', dataModelInfo?: DataModelInfo): string {
  const safeName = screenName.replace(/[^a-zA-Z0-9_]/g, '');
  const modelName = dataModelInfo?.modelName || (dataModelInfo?.bindings?.length ? `${safeName}Model` : '');

  const bindingSnippet = modelName
    ? `    // RULE 1: Bind Data Model BEFORE LoadDocument per VaCuus Architecture
    // Data model name '${modelName}' matches RML <body data-model="${modelName}">
    BindDataModel(TEXT("${modelName}"), &DataModel);`
    : `    // RULE 1: Bind Data Models BEFORE LoadDocument
    // If you have a custom struct or UObject data model:
    // BindDataModel(TEXT("${safeName}Model"), &MyDataModelInstance);`;

  return `// Copyright (c) 2026. Generated by Kormatal RML UI Editor for Unreal Engine 5.
#include "${safeName}View.h"
#include "GameFramework/PlayerController.h"

UVaCuus${safeName}View::UVaCuus${safeName}View()
{
    DocumentPath = TEXT("${safeName}/${safeName.toLowerCase()}.rml");
    bConfigureInputModeOnOpen = true;
}

bool UVaCuus${safeName}View::InitializeActiveUI(APlayerController* PlayerController, int32 ZOrder)
{
${bindingSnippet}

    // RULE 2: Load the RML document from Content/DevUI/
    const bool bLoaded = LoadDocument(DocumentPath);
    if (!bLoaded)
    {
        UE_LOG(LogTemp, Error, TEXT("UVaCuus${safeName}View: Failed to load document '%s'"), *DocumentPath);
        return false;
    }

    // RULE 3: Add view to active viewport
    AddToViewport(ZOrder);

    // RULE 4: Configure Active UI Input Mode so UI is interactive
    if (bConfigureInputModeOnOpen && PlayerController)
    {
        FInputModeGameAndUI InputMode;
        InputMode.SetLockMouseToViewportBehavior(EMouseLockMode::DoNotLock);
        InputMode.SetHideCursorDuringCapture(false);
        PlayerController->SetInputMode(InputMode);
        PlayerController->bShowMouseCursor = true;
    }

    UE_LOG(LogTemp, Log, TEXT("UVaCuus${safeName}View: Active UI initialized successfully from '%s'"), *DocumentPath);
    return true;
}

void UVaCuus${safeName}View::CloseActiveUI(APlayerController* PlayerController)
{
    CloseDocument();
    RemoveFromViewport();

    if (PlayerController)
    {
        FInputModeGameOnly InputMode;
        PlayerController->SetInputMode(InputMode);
        PlayerController->bShowMouseCursor = false;
    }
}
`;
}

